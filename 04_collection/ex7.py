# 집합 기초

# ===========================================================
#  집합 (set): 여러 객체를 순서 없이 중복을 허용하지 않고 저장하는 변경 가능한 자료형
#  집합의 특징
#  1. (mutable, 변경가능)
#  2. (iterable, 반복가능)
#  3. (sequence X, 인덱싱, 슬라이싱 불가)
#  4. (중복 불가)
# ===========================================================

# 집합 생성
# set={}  #딕셔너리
s= set()
print(type(s))
print({1,2,2,2,5})
print({100,8,30})

# ===========================================================
# 1. 집합은 mutable하다. (변경 가능)
# ===========================================================

a= {1,2,3}
a.update({3,4})

a.update([5, 6])
print(a)

a.remove(3)  # 원본 변경
print(a)

# ===========================================================
# 2. 집합은 iterable하다. (반복 가능)
# ===========================================================

# 집합 순회
for i in a:
    print(i)


# ===========================================================
# 3. 집합은 sequence 객체가 아니다. (인덱싱, 슬라이싱 불가)
# ===========================================================

# a[0] = 10 # 인덱스가 없다. 할당되지 않는다. __setitem__

# ===========================================================
# 4. 집합은 중복을 허용하지 않는다.
# ===========================================================

# a = (10,20,30,30)
# print(a)

# ===========================================================
#  파이썬 내장 함수
# ===========================================================

s={10,20,30}
print(len(s))
print(sum(s))
print(min(s))
print(max(s))

# 집합 합치기
s2={40,50}
print(s.union(s2))  #update와 동일

# 집합 반복하기
# print(s*2)

# 멤버십 연산자
print(10 in s)
print(1 in s)